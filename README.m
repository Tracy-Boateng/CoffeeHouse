# Coffee House Website ☕

A modern and aesthetic coffee house website built using HTML, CSS, and JavaScript to create a warm and engaging café experience online.

## Overview

This project is a fully responsive coffee house website focused on clean design, smooth user experience, and modern front-end development practices. The website highlights a cozy coffee shop atmosphere through elegant layouts, appealing visuals, and interactive elements.

## Features

- Fully responsive design
- Modern and aesthetic user interface
- Interactive navigation
- Smooth scrolling effects
- Coffee menu section
- About and contact sections
- Organized and clean layout
- Mobile-friendly experience

## Technologies Used

- HTML5
- CSS3
- JavaScript

## Purpose

The purpose of this project was to strengthen my front-end web development skills while building a visually appealing and functional website from scratch.

## What I Learned

Through this project, I improved my understanding of:

- Responsive web design
- Website structure using HTML
- Styling and layouts with CSS
- Interactivity using JavaScript
- UI/UX design principles
- Creating modern and aesthetic web experiences

